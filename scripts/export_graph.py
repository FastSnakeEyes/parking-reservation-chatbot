"""Export the LangGraph diagrams to docs/graph.md (Mermaid, rendered by GitHub).

    uv run python -m scripts.export_graph          # docs/graph.md
    uv run python -m scripts.export_graph --png    # also docs/graph.png

The graphs are built exactly as the app builds them, but with a stand-in model
and an in-memory checkpointer - no database, Redis or OpenAI key is needed,
since only their structure is drawn.

--png renders ParkingGraph through mermaid.ink, a public rendering service
(LangGraph's default PNG renderer): only the diagram text - node names and
edges - is sent, but it is a network call, so it is opt-in.
"""

import argparse
from pathlib import Path

from app.ai.agents import build_admin_agent, build_user_agent
from app.ai.graph import _build_graph
from app.constants import BASE_DIR
from langchain_core.language_models.fake_chat_models import FakeMessagesListChatModel
from langchain_core.runnables.graph_mermaid import draw_mermaid_png
from langgraph.checkpoint.memory import InMemorySaver

DOCS_DIR = BASE_DIR / "docs"


class _StructureOnlyModel(FakeMessagesListChatModel):
    """Lets the agents be built without an LLM; it is never called."""

    def bind_tools(self, tools, *, tool_choice=None, **kwargs):
        return self


def build_diagrams() -> dict[str, str]:
    """Mermaid source for each graph, keyed by its title."""
    model = _StructureOnlyModel(responses=[])
    return {
        "ParkingGraph (app/ai/graph.py)": _build_graph(model, InMemorySaver()).get_graph().draw_mermaid(),
        "User agent (app/ai/agents.py)": build_user_agent(model).get_graph().draw_mermaid(),
        "Admin agent (app/ai/agents.py)": build_admin_agent(model).get_graph().draw_mermaid(),
    }


def render_markdown(diagrams: dict[str, str]) -> str:
    sections = [
        "# LangGraph diagrams",
        "",
        "Generated by `uv run python -m scripts.export_graph` from the code - regenerate after",
        "changing a graph. Solid arrows are fixed edges; dotted arrows are conditional (decided",
        "at run time).",
        "",
        "- **ParkingGraph** - one conversation: `user_agent` handles the customer's turn and, after",
        "  `confirm`, routes to `admin` (the human-in-the-loop pause), then `record` (MCP / status)",
        "  and `notification` (the customer's pop-up).",
        "- **User agent** - runs inside `user_agent`; its middleware (PII redaction, history",
        "  summarization, ending the turn after a review) shows up as extra steps.",
        "- **Admin agent** - runs inside `admin`; `HumanInTheLoopMiddleware.after_model` is where",
        "  it pauses for the administrator's decision.",
    ]
    for title, mermaid in diagrams.items():
        sections += ["", f"## {title}", "", "```mermaid", mermaid.strip(), "```"]
    return "\n".join(sections) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Export the LangGraph diagrams")
    parser.add_argument("--png", action="store_true", help="also render docs/graph.png via mermaid.ink")
    args = parser.parse_args()

    diagrams = build_diagrams()
    markdown_path = DOCS_DIR / "graph.md"
    markdown_path.write_text(render_markdown(diagrams), encoding="utf-8")
    print(f"Wrote {markdown_path.relative_to(BASE_DIR)}")

    if args.png:
        parking_graph = next(iter(diagrams.values()))
        # Left-to-right reads better on a wide page or slide than the default top-down.
        png = draw_mermaid_png(parking_graph.replace("graph TD;", "graph LR;"), background_color="white", padding=24)
        png_path = Path(DOCS_DIR / "graph.png")
        png_path.write_bytes(png)
        print(f"Wrote {png_path.relative_to(BASE_DIR)}")


if __name__ == "__main__":
    main()
